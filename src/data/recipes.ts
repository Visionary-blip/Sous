import type { Recipe, RecipeIngredient } from "../types";

/** Compact recipe definition: "name|amount" strings, with a trailing "?" for optional. */
interface RecipeDef {
  id: string;
  title: string;
  minutes: number;
  servings: number;
  tags: string[];
  ingredients: string[];
  steps: string[];
}

function parseIngredient(spec: string): RecipeIngredient {
  const optional = spec.endsWith("?");
  const [name, amount] = (optional ? spec.slice(0, -1) : spec).split("|");
  return { name: name.trim(), amount: amount?.trim(), optional: optional || undefined };
}

